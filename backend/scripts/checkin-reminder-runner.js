#!/usr/bin/env node

function defaultRequestId(date = new Date()) {
  return `checkin-reminders-${date.toISOString().slice(0, 16).replace(/[-:T]/g, "")}`;
}

function normalizeText(value) {
  return String(value || "").trim();
}

function parseArgs(argv) {
  const args = {
    baseUrl: process.env.ROOT_JOB_BASE_URL ||
      process.env.ROOT_CALIBRATION_BASE_URL ||
      process.env.ROOT_PUBLIC_BASE_URL ||
      `http://127.0.0.1:${process.env.PORT || 8787}`,
    adminToken: process.env.ROOT_ADMIN_JOB_TOKEN || process.env.ROOT_ADMIN_TOKEN || "",
    dryRun: true,
    limit: Number(process.env.ROOT_CHECKIN_REMINDER_JOB_LIMIT || 50),
    now: "",
    requestId: "",
    json: false,
    help: false,
  };
  for (let index = 0; index < argv.length; index += 1) {
    const item = argv[index];
    if (item === "--base-url") args.baseUrl = argv[index += 1] || args.baseUrl;
    else if (item === "--admin-token") args.adminToken = argv[index += 1] || "";
    else if (item === "--dry-run") args.dryRun = true;
    else if (item === "--execute") args.dryRun = false;
    else if (item === "--limit") args.limit = Number(argv[index += 1] || args.limit);
    else if (item === "--now") args.now = normalizeText(argv[index += 1]);
    else if (item === "--request-id") args.requestId = normalizeText(argv[index += 1]);
    else if (item === "--json") args.json = true;
    else if (item === "--help" || item === "-h") args.help = true;
  }
  args.baseUrl = args.baseUrl.replace(/\/+$/, "");
  args.limit = Math.max(1, Math.min(200, Number(args.limit) || 50));
  if (!args.dryRun && !args.requestId) args.requestId = defaultRequestId();
  return args;
}

function buildHelpText() {
  return [
    "Usage: npm run checkin-reminders --prefix backend -- [options]",
    "",
    "Options:",
    "  --dry-run                 Preview due reminders without writing sends",
    "  --execute                 Send due reminders and write delivery records",
    "  --limit <n>               Max reminders to scan, default 50",
    "  --now <iso>               Override current time for verification",
    "  --request-id <id>         Required for execute mode; generated by default if omitted",
    "  --base-url <url>          Override ROOT_JOB_BASE_URL",
    "  --admin-token <token>     Override ROOT_ADMIN_JOB_TOKEN",
    "  --json                    Print JSON bundle",
    "  --help                    Show this help",
    "",
  ].join("\n");
}

async function postCheckinReminderJob(args) {
  const body = {
    dryRun: args.dryRun,
    limit: args.limit,
    now: args.now || undefined,
    requestId: args.requestId || undefined,
  };
  const headers = { "Content-Type": "application/json" };
  if (args.requestId) headers["X-Request-Id"] = args.requestId;
  if (args.adminToken) {
    headers["X-Admin-Token"] = args.adminToken;
    headers["X-ROOT-ADMIN-TOKEN"] = args.adminToken;
  }
  const response = await fetch(`${args.baseUrl}/api/v1/jobs/checkin-reminders`, {
    method: "POST",
    headers,
    body: JSON.stringify(body),
  });
  const payload = await response.json();
  return {
    ok: response.ok && payload.code === 0,
    code: payload.code,
    message: payload.message,
    data: payload.data,
    request: body,
  };
}

async function collectCheckinReminderJob(args) {
  return postCheckinReminderJob(args);
}

function buildCheckinReminderJobReport(bundle) {
  const data = bundle.data || {};
  const results = data.results || [];
  const statusCounts = results.reduce((acc, item) => {
    acc[item.status || "UNKNOWN"] = (acc[item.status || "UNKNOWN"] || 0) + 1;
    return acc;
  }, {});
  const lines = [
    "# ROOT 打卡提醒 Job 报告",
    "",
    `请求结果：${bundle.ok ? "OK" : "FAILED"}`,
    `消息：${bundle.message || "ok"}`,
    `模式：${data.dryRun ? "DRY_RUN" : "EXECUTE"}`,
    `request_id：${bundle.request && bundle.request.requestId ? bundle.request.requestId : "-"}`,
    `扫描任务数：${data.scannedCount || 0}`,
    "",
    "## 状态汇总",
    ...Object.entries(statusCounts).map(([status, count]) => `- ${status}：${count}`),
    ...(Object.keys(statusCounts).length ? [] : ["- 暂无到期提醒"]),
    "",
    "## 执行结果",
    ...results.map((item) => `- ${item.jobId || "-"} / ${item.status || "-"}${item.errorCode ? ` / ${item.errorCode}` : ""}`),
    ...(results.length ? [] : ["- 暂无执行结果"]),
  ];
  return `${lines.join("\n")}\n`;
}

function determineExitCode(bundle) {
  if (!bundle.ok) return 2;
  const failed = (bundle.data && bundle.data.results || []).some((item) => item.status === "FAILED");
  return failed ? 3 : 0;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    process.stdout.write(buildHelpText());
    return;
  }
  try {
    const bundle = await collectCheckinReminderJob(args);
    if (args.json) process.stdout.write(`${JSON.stringify(bundle, null, 2)}\n`);
    else process.stdout.write(buildCheckinReminderJobReport(bundle));
    process.exitCode = determineExitCode(bundle);
  } catch (error) {
    process.stderr.write(`打卡提醒 Job 失败：${error.message}\n`);
    process.exitCode = 1;
  }
}

if (require.main === module) {
  main();
}

module.exports = {
  buildCheckinReminderJobReport,
  buildHelpText,
  collectCheckinReminderJob,
  defaultRequestId,
  determineExitCode,
  parseArgs,
};
