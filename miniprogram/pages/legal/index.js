Page({
  data: {
    doc: docs.agreement,
    documentType: "agreement",
    privacyNotice: null,
  },

  onLoad(options = {}) {
    const type = options.type === "privacy" ? "privacy" : "agreement";
    const doc = docs[type];
    this.setData({ doc, documentType: type });
    wx.setNavigationBarTitle({ title: doc.title });
    if (type === "privacy") this.loadPrivacyNotice();
  },

  async loadPrivacyNotice() {
    try {
      const notice = await request({ url: "/api/v1/privacy/notice" });
      if (notice && notice.configured) this.setData({ privacyNotice: notice });
    } catch (_) {
      // The static policy remains available when the public metadata request fails.
    }
  },
});
